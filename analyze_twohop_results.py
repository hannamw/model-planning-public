        if args.csv_output:
            performance_df.to_csv(args.csv_output, index=False)
            print(f"Performance table saved to {args.csv_output}")
        
        # Show detailed metrics if requested
        if args.detailed:
            print("\n" + "="*50)
            print("DETAILED METRICS")
            print("="*50)
            
            # Sort models by size function (same as used elsewhere)
            def extract_model_size(model_name: str) -> float:
                """Extract the numerical size from model name (e.g., 'Qwen/Qwen3-14B' -> 14.0)"""
