#!/usr/bin/env python3
"""
Analyze TwoHopFact evaluation results and create performance tables.

This script reads all CSV files generated by two_hop_eval_local.py and creates
a comprehensive performance table showing accuracy for each model on both
1-hop and 2-hop reasoning tasks.
"""

import argparse
import pandas as pd
from pathlib import Path
import re
from typing import Dict, List, Tuple
import numpy as np


def load_results_from_directory(results_dir: Path) -> pd.DataFrame:
    """Load all CSV result files from the results directory."""
    print(f"Loading results from {results_dir}")
    
    all_results = []
    csv_files = list(results_dir.glob("*.csv"))
    
    if not csv_files:
        raise ValueError(f"No CSV files found in {results_dir}")
    
    for csv_file in csv_files:
        print(f"  Loading {csv_file.name}")
        df = pd.read_csv(csv_file)
        all_results.append(df)
    
    # Combine all results
    combined_df = pd.concat(all_results, ignore_index=True)
    print(f"Loaded {len(combined_df)} total results from {len(csv_files)} files")
    
    return combined_df


def calculate_accuracy_metrics(df: pd.DataFrame) -> Dict:
    """Calculate various accuracy metrics for a dataframe."""
    total_examples = len(df)
    
    if total_examples == 0:
        return {
            "total_examples": 0,
            "non_empty_responses": 0,
            "non_empty_rate": 0.0,
            "exact_matches": 0,
            "exact_match_accuracy": 0.0,
            "substring_matches": 0,
            "substring_match_accuracy": 0.0,
            "case_insensitive_matches": 0,
            "case_insensitive_accuracy": 0.0
        }
    
    # Count non-empty responses
    non_empty_responses = len(df[df['generated_answer'].str.len() > 0])
    non_empty_rate = non_empty_responses / total_examples
    
    # Calculate different types of accuracy
    exact_matches = 0
    substring_matches = 0
    case_insensitive_matches = 0
    
    for _, row in df.iterrows():
        gt_answer = str(row['ground_truth_answer']).strip()
        gen_answer = str(row['generated_answer']).strip()
        
        # Skip if either is empty or nan
        if not gt_answer or not gen_answer or gt_answer == 'nan' or gen_answer == 'nan':
            continue
        
        # Exact match
        if gt_answer == gen_answer:
            exact_matches += 1
        
        # Case-insensitive exact match
        if gt_answer.lower() == gen_answer.lower():
            case_insensitive_matches += 1
        
        # Substring match (ground truth is substring of generated answer)
        if gt_answer.lower() in gen_answer.lower():
            substring_matches += 1
    
    return {
        "total_examples": total_examples,
        "non_empty_responses": non_empty_responses,
        "non_empty_rate": non_empty_rate,
        "exact_matches": exact_matches,
        "exact_match_accuracy": exact_matches / total_examples,
        "substring_matches": substring_matches,
        "substring_match_accuracy": substring_matches / total_examples,
        "case_insensitive_matches": case_insensitive_matches,
        "case_insensitive_accuracy": case_insensitive_matches / total_examples
    }


def create_performance_table(df: pd.DataFrame) -> pd.DataFrame:
    """Create a performance table with models as rows and metrics as columns."""
    
    # Get unique models and modes
    models = df['model'].unique()
    modes = sorted(df['mode'].unique())
    
    # Sort models by size (extract numerical size from model name)
    def extract_model_size(model_name: str) -> float:
        """Extract the numerical size from model name (e.g., 'Qwen/Qwen3-14B' -> 14.0)"""
        model_name = model_name.split("/")[-1] if "/" in model_name else model_name
        # Look for pattern like "1.7B" or "14B" in the model name
        import re
        match = re.search(r'(\d+\.?\d*)B', model_name)
        if match:
            return float(match.group(1))
        return 0.0  # Default for models without clear size indicator
    
    models = sorted(models, key=extract_model_size)
    
    results = []
    
    for model in models:
        model_data = df[df['model'] == model]
        
        # Clean model name for display
        model_name = model.split("/")[-1] if "/" in model else model
        
        row = {"Model": model_name}
        
        for mode in modes:
            mode_data = model_data[model_data['mode'] == mode]
            
            if len(mode_data) == 0:
                # No data for this model/mode combination
                row[f"{mode}_examples"] = 0
                row[f"{mode}_non_empty_rate"] = 0.0
                row[f"{mode}_exact_accuracy"] = 0.0
                row[f"{mode}_substring_accuracy"] = 0.0
                row[f"{mode}_case_insensitive_accuracy"] = 0.0
            else:
                metrics = calculate_accuracy_metrics(mode_data)
                row[f"{mode}_examples"] = metrics["total_examples"]
                row[f"{mode}_non_empty_rate"] = metrics["non_empty_rate"]
                row[f"{mode}_exact_accuracy"] = metrics["exact_match_accuracy"]
                row[f"{mode}_substring_accuracy"] = metrics["substring_match_accuracy"]
                row[f"{mode}_case_insensitive_accuracy"] = metrics["case_insensitive_accuracy"]
        
        results.append(row)
    
    return pd.DataFrame(results)


def format_performance_table(df: pd.DataFrame) -> str:
    """Format the performance table for nice printing."""
    
    # Create a formatted string representation
    output = []
    
    # Header
    output.append("=" * 100)
    output.append("QWEN3 MODELS PERFORMANCE ON TWOHOPFACT DATASET")
    output.append("=" * 100)
    output.append("")
    
    # Check what modes we have
    modes = []
    for col in df.columns:
        if "_examples" in col:
            mode = col.replace("_examples", "")
            modes.append(mode)
    
    modes = sorted(set(modes))
    
    # Create table header
    header = ["Model"]
    for mode in modes:
        header.extend([f"{mode} Examples", f"{mode} Non-Empty %", f"{mode} Exact %", f"{mode} Substring %", f"{mode} Case-Insens %"])
    
    # Format table
    col_widths = [max(15, len(h)) for h in header]
    
    # Print header
    header_line = " | ".join(h.ljust(w) for h, w in zip(header, col_widths))
    output.append(header_line)
    output.append("-" * len(header_line))
    
    # Print rows
    for _, row in df.iterrows():
        row_values = [str(row["Model"])]
        
        for mode in modes:
            examples = row.get(f"{mode}_examples", 0)
            non_empty = row.get(f"{mode}_non_empty_rate", 0.0)
            exact = row.get(f"{mode}_exact_accuracy", 0.0)
            substring = row.get(f"{mode}_substring_accuracy", 0.0)
            case_insens = row.get(f"{mode}_case_insensitive_accuracy", 0.0)
            
            row_values.extend([
                str(examples),
                f"{non_empty:.1%}",
                f"{exact:.1%}",
                f"{substring:.1%}",
                f"{case_insens:.1%}"
            ])
        
        formatted_row = " | ".join(val.ljust(w) for val, w in zip(row_values, col_widths))
        output.append(formatted_row)
    
    output.append("")
    output.append("Accuracy Metrics:")
    output.append("- Non-Empty %: Percentage of responses that are not empty")
    output.append("- Exact %: Percentage of exact matches with ground truth")
    output.append("- Substring %: Percentage where ground truth is substring of generated answer")
    output.append("- Case-Insens %: Percentage of case-insensitive exact matches")
    
    return "\n".join(output)


def create_summary_statistics(df: pd.DataFrame) -> str:
    """Create summary statistics about the evaluation."""
    
    # Sort models by size function
    def extract_model_size(model_name: str) -> float:
        """Extract the numerical size from model name (e.g., 'Qwen/Qwen3-14B' -> 14.0)"""
        model_name = model_name.split("/")[-1] if "/" in model_name else model_name
        # Look for pattern like "1.7B" or "14B" in the model name
        import re
        match = re.search(r'(\d+\.?\d*)B', model_name)
        if match:
            return float(match.group(1))
        return 0.0  # Default for models without clear size indicator
    
    output = []
    output.append("EVALUATION SUMMARY")
    output.append("=" * 50)
    output.append(f"Total examples processed: {len(df)}")
    output.append(f"Models evaluated: {df['model'].nunique()}")
    output.append(f"Modes evaluated: {', '.join(sorted(df['mode'].unique()))}")
    output.append(f"Temperature used: {df['temperature'].iloc[0] if len(df) > 0 else 'N/A'}")
    output.append(f"Max tokens: {df['max_tokens'].iloc[0] if len(df) > 0 else 'N/A'}")
    output.append("")
    
    # Per-model summary (sorted by size)
    for model in sorted(df['model'].unique(), key=extract_model_size):
        model_data = df[df['model'] == model]
        model_name = model.split("/")[-1] if "/" in model else model
        
        output.append(f"{model_name}:")
        for mode in sorted(model_data['mode'].unique()):
            mode_data = model_data[model_data['mode'] == mode]
            metrics = calculate_accuracy_metrics(mode_data)
            output.append(f"  {mode}: {metrics['total_examples']} examples, {metrics['substring_match_accuracy']:.1%} accuracy")
        output.append("")
    
    return "\n".join(output)


